-- Tables of conservation-service: rescue cases, treatment, resources, allocations and programmes.
-- Everything is inside the schema "conservation", so it does not touch the tables of the
-- platform app or the other services even when all of them use one database.
-- This file runs every time the service starts. "if not exists" means nothing happens
-- when the tables are already there.
-- incident_id, animal_id and a patrol's target_id are ids of records owned by OTHER services.
-- They are saved as text and have no foreign key.

create schema if not exists conservation;

create table if not exists conservation.rescue_cases (
    id                       bigint generated by default as identity primary key,
    rescue_code              varchar(20)   not null unique,
    incident_id              varchar(40),
    incident_code            varchar(40),
    animal_id                varchar(40),
    animal_code              varchar(40),
    assigned_staff_name      varchar(120),
    stage                    varchar(20)   not null default 'REPORTED',
    summary                  varchar(1000) not null,
    destination              varchar(200),
    outcome                  varchar(500),
    release_review_status    varchar(12)   not null default 'NONE',
    release_review_notes     varchar(1000),
    release_reviewed_by_name varchar(120),
    release_reviewed_at      timestamp,
    opened_by_name           varchar(120),
    opened_at                timestamp     not null,
    closed_at                timestamp,
    constraint rescue_stage_check check (stage in
        ('REPORTED', 'RESCUED', 'UNDER_TREATMENT', 'REHABILITATION', 'RELEASED', 'TRANSFERRED')),
    constraint rescue_review_check check (release_review_status in ('NONE', 'REQUESTED', 'APPROVED', 'REJECTED'))
);

create table if not exists conservation.rescue_stage_history (
    id              bigint generated by default as identity primary key,
    rescue_case_id  bigint       not null references conservation.rescue_cases (id),
    old_stage       varchar(20),
    new_stage       varchar(20)  not null,
    action          varchar(200) not null,
    notes           varchar(1000),
    changed_by_name varchar(120),
    changed_at      timestamp    not null
);

create table if not exists conservation.treatment_records (
    id               bigint generated by default as identity primary key,
    rescue_case_id   bigint       not null references conservation.rescue_cases (id),
    recorded_by_name varchar(120),
    treatment        varchar(500) not null,
    notes            varchar(1000),
    recorded_at      timestamp    not null
);

-- vehicles and equipment
create table if not exists conservation.resources (
    id            bigint generated by default as identity primary key,
    resource_code varchar(20)  not null unique,
    category      varchar(20)  not null,
    name          varchar(120) not null,
    status        varchar(20)  not null default 'AVAILABLE',
    notes         varchar(500),
    constraint resources_category_check check (category in
        ('VEHICLE', 'GPS_DEVICE', 'CAMERA', 'RADIO', 'MEDICAL_KIT', 'OTHER')),
    constraint resources_status_check check (status in ('AVAILABLE', 'ALLOCATED', 'MAINTENANCE'))
);

create table if not exists conservation.resource_allocations (
    id                bigint generated by default as identity primary key,
    resource_id       bigint      not null references conservation.resources (id),
    target_type       varchar(20) not null,
    target_id         varchar(40) not null,
    target_code       varchar(40),
    allocated_at      timestamp   not null,
    allocated_by_name varchar(120),
    released_at       timestamp,
    released_by_name  varchar(140),
    notes             varchar(500),
    override_used     boolean     not null default false,
    constraint allocations_target_check check (target_type in ('PATROL', 'RESCUE_CASE'))
);

-- Last line of defence against double allocation: the database itself allows at most one
-- active (not yet released) allocation per resource.
create unique index if not exists uq_one_active_allocation on conservation.resource_allocations (resource_id) where released_at is null;

create table if not exists conservation.programmes (
    id               bigint generated by default as identity primary key,
    programme_code   varchar(20)  not null unique,
    name             varchar(150) not null,
    description      varchar(1000),
    target_quantity  integer      not null check (target_quantity > 0),
    unit             varchar(40),
    start_date       date,
    due_date         date,
    status           varchar(20)  not null default 'PLANNED',
    owner_staff_name varchar(120),
    team             varchar(60),
    constraint programmes_status_check check (status in ('PLANNED', 'ACTIVE', 'ON_HOLD', 'COMPLETED'))
);

create table if not exists conservation.programme_activities (
    id                 bigint generated by default as identity primary key,
    programme_id       bigint       not null references conservation.programmes (id),
    description        varchar(500) not null,
    quantity_completed integer      not null check (quantity_completed > 0),
    completed_at       timestamp    not null,
    recorded_by_name   varchar(120)
);

create index if not exists idx_rescue_stage on conservation.rescue_cases (stage);
create index if not exists idx_rescue_incident on conservation.rescue_cases (incident_id);
create index if not exists idx_rescue_animal on conservation.rescue_cases (animal_id);
create index if not exists idx_rescue_history_case on conservation.rescue_stage_history (rescue_case_id);
create index if not exists idx_treatment_case on conservation.treatment_records (rescue_case_id);
create index if not exists idx_resources_status on conservation.resources (status);
create index if not exists idx_allocations_resource on conservation.resource_allocations (resource_id);
create index if not exists idx_allocations_target on conservation.resource_allocations (target_type, target_id);
create index if not exists idx_activities_programme on conservation.programme_activities (programme_id);

-- counters for new codes (RES-032, PRG-005 ...). The demo data uses the lower numbers.
create sequence if not exists conservation.rescue_code_seq start with 32;
create sequence if not exists conservation.programme_code_seq start with 5;
